"""Evaluation: retrieval metrics, generation metrics, abstention and numeric
exact-match over the golden set.

Offline, faithfulness and relevance are computed with transparent heuristics
(numbers and terms must be backed by the cited pages). With an API key the
LLM-as-judge versions are used instead. Both are reported with their method.
"""
import json
import math
import os
import re
import statistics
import time
from itertools import permutations
from pathlib import Path

from finlens import llm
from finlens.config import Settings
from finlens.db import connect
from finlens.query.understanding import understand
from finlens.retrieval.search import search
from finlens.service import FinLens
from finlens.text import content_tokens, numbers_in

DEBUG = os.getenv("FINLENS_EVAL_DEBUG") == "1"
GOLDEN = Path(__file__).resolve().parent.parent / "eval" / "golden.jsonl"
HOLDOUT = Path(__file__).resolve().parent.parent / "eval" / "holdout.jsonl"


def _read_jsonl(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def load_golden(path: Path = GOLDEN, include_holdout: bool = True) -> list[dict]:
    """Golden set (regenerated by make_sample_data.py) plus the hand-written held-out set.

    The held-out file is never regenerated: its questions use phrasings, synonyms and
    out-of-corpus asks that the system was not tuned against, so it is the fairer number.
    """
    rows = _read_jsonl(path)
    if include_holdout and path == GOLDEN and HOLDOUT.exists():
        rows += _read_jsonl(HOLDOUT)
    return rows


def bootstrap_ci(values: list[float], n_boot: int = 2000, seed: int = 0) -> tuple[float, float] | None:
    """95% percentile bootstrap interval for a mean. Wide intervals mean 'too few questions to say'."""
    import random
    vals = [float(v) for v in values if v is not None]
    if len(vals) < 2:
        return None
    rng = random.Random(seed)
    means = sorted(statistics.mean(rng.choices(vals, k=len(vals))) for _ in range(n_boot))
    return round(means[int(0.025 * n_boot)], 3), round(means[int(0.975 * n_boot) - 1], 3)


def confidence_intervals(rows: list[dict]) -> dict:
    """Bootstrap 95% CIs plus sample sizes for the headline metrics."""
    unans = [r for r in rows if r["type"] == "unanswerable" and "abstain_correct" in r]
    ans = [r for r in rows if r["type"] != "unanswerable" and "abstained" in r]
    pick = lambda rs, k: [float(r[k]) for r in rs if r.get(k) is not None]  # noqa: E731
    spec = {"recall@5": (rows, "recall@5"), "numeric_em": (rows, "numeric_em"), "faithfulness": (rows, "faithfulness"),
            "abstention_accuracy": (unans, "abstain_correct"), "false_abstention_rate": (ans, "abstained")}
    return {k: {"n": len(pick(rs, f)), "ci95": bootstrap_ci(pick(rs, f))} for k, (rs, f) in spec.items()}


# ---------------------------------------------------------------------------
# Retrieval metrics (page-level relevance)
# ---------------------------------------------------------------------------
def retrieval_metrics(ranked_pages: list[tuple], gold: set) -> dict:
    seen, pages = set(), []
    for p in ranked_pages:
        if p not in seen:
            seen.add(p)
            pages.append(p)
    rel = [1 if p in gold else 0 for p in pages]
    recall = lambda k: len(gold & set(pages[:k])) / len(gold)  # noqa: E731
    first = next((i for i, r in enumerate(rel) if r), None)
    dcg = sum(r / math.log2(i + 2) for i, r in enumerate(rel[:10]))
    idcg = sum(1 / math.log2(i + 2) for i in range(min(len(gold), 10)))
    return {"recall@5": recall(5), "recall@20": recall(20), "mrr": 1 / (first + 1) if first is not None else 0.0,
            "ndcg@10": dcg / idcg if idcg else 0.0}


def retrieve_for_eval(conn, q: dict, s: Settings, years: list[str]) -> list[tuple]:
    plan = understand(q["question"], [], s, years)
    rs = s.with_(use_parent_expansion=False, use_compression=False)
    levels = ("summary", "child", "table") if q["type"] == "broad" else ("child", "table")
    hits = search(conn, plan.query, plan.filters, rs, variants=plan.variants or None, levels=levels, k=20)
    return [(h["doc_id"], h["page"]) for h in hits]


# ---------------------------------------------------------------------------
# Generation metrics
# ---------------------------------------------------------------------------
def is_abstention(r: dict) -> bool:
    return r["answer"].startswith("I don't know")


def numeric_em(answer: str, expected: list[float]) -> bool:
    got = numbers_in(re.sub(r"\[[^\]]*\]", "", answer))
    return all(any(abs(g - e) <= max(0.051, abs(e) * 0.001) for g in got) for e in expected)


def page_text(conn, doc: str, page: int) -> str:
    """Text of a cited page, plus the document's company and period (a citation implies both)."""
    meta = conn.execute("SELECT company, fiscal_year, quarter FROM documents WHERE doc_id=?", (doc,)).fetchone()
    head = " ".join(x for x in (meta or []) if x)
    return head + " " + " ".join(r[0] for r in conn.execute(
        "SELECT text FROM chunks WHERE doc_id=? AND page=? AND active=1 AND level IN ('parent','table')", (doc, page)))


# Words the answer templates use to describe numbers; they are analysis, not claims from the page.
ANALYSIS_WORDS = {"higher", "lower", "difference", "calculated", "overall", "rose", "fell", "percentage", "points",
                  "compared", "latest", "reported", "unchanged", "first", "then", "had", "current"}


def _derived(nums: list[float]) -> list[float]:
    """Numbers a calculator could derive from two source numbers (differences, % change, ratios)."""
    out = []
    for a, b in permutations(nums[:150], 2):
        out += [a - b, (a - b) / b * 100 if b else 0, a / b if b else 0]
    return out


def faithfulness(conn, r: dict) -> float:
    """Share of answer sentences whose numbers and terms are backed by the cited pages."""
    if is_abstention(r):
        return 1.0
    sents = [x for x in re.split(r"(?<=[.!?])\s+(?=[A-Z])", r["answer"])
             if x.strip() and not x.startswith("Not available")]      # stated gaps are not claims
    all_cites = re.findall(r"\[([A-Za-z0-9_]+), p\.(\d+)\]", r["answer"])
    if not all_cites:
        return 0.0
    all_text = " ".join(page_text(conn, d, int(p)) for d, p in set(all_cites))
    derived = _derived(sorted(set(numbers_in(all_text))))
    ok = 0
    for sent in sents:
        cites = re.findall(r"\[([A-Za-z0-9_]+), p\.(\d+)\]", sent) or all_cites
        context = " ".join(page_text(conn, d, int(p)) for d, p in set(cites)) + " " + all_text
        clean = re.sub(r"\[[^\]]*\]", "", sent)
        src_nums = numbers_in(context)
        pool = src_nums + derived
        nums_ok = all(any(abs(abs(n) - abs(p)) <= max(0.051, abs(p) * 0.001) for p in pool)
                      for n in numbers_in(re.sub(r"FY\d\d|Q[1-4]", "", clean)))
        terms = [t for t in content_tokens(clean) if not t.replace(".", "").isdigit() and t not in ANALYSIS_WORDS]
        ctx_terms = set(content_tokens(context))
        term_ratio = sum(t in ctx_terms for t in terms) / len(terms) if terms else 1.0
        ok += nums_ok and term_ratio >= 0.5
        if DEBUG and not (nums_ok and term_ratio >= 0.5):
            print(f"    unsupported: {sent[:120]} (nums_ok={nums_ok}, terms={term_ratio:.2f})")
    return ok / len(sents) if sents else 1.0


def relevance(question: str, answer: str) -> float:
    q = set(content_tokens(question))
    return len(q & set(content_tokens(answer))) / len(q) if q else 1.0


def llm_judge(question: str, answer: str, context: str) -> dict:
    out = llm.complete_json(
        f"Question: {question}\nAnswer: {answer}\nSource pages: {context[:6000]}\n\nScore from 0 to 1: "
        f'faithfulness (claims supported by sources) and relevance (answers the question). '
        f'JSON: {{"faithfulness": x, "relevance": y}}')
    return out if isinstance(out, dict) else {}


# ---------------------------------------------------------------------------
def evaluate(s: Settings, questions: list[dict], retrieval: bool = True, generation: bool = True) -> dict:
    s = s.with_(use_cache=False)
    conn = connect(s.db_path)
    years = [r[0] for r in conn.execute("SELECT DISTINCT fiscal_year FROM documents ORDER BY fiscal_year")]
    app = FinLens(s) if generation else None
    per_q = []
    for q in questions:
        row = {"id": q["id"], "type": q["type"], "source": q.get("source", "synthetic")}
        gold = {(g["doc"], g["page"]) for g in q["gold"]}
        if retrieval and gold:
            row.update(retrieval_metrics(retrieve_for_eval(conn, q, s, years), gold))
        if generation:
            t0 = time.perf_counter()
            r = app.ask(q["question"], use_memory=False)
            row["latency_ms"] = (time.perf_counter() - t0) * 1000
            row["cost_usd"] = r["cost_usd"]
            row["answer"] = r["answer"]
            row["abstained"] = is_abstention(r)
            row["synthesized"] = bool(r.get("synthesized"))      # share of answers an LLM wrote and verification accepted
            row["abstain_correct"] = row["abstained"] == (q["type"] == "unanswerable")
            if q["type"] != "unanswerable":
                if q["numbers"]:
                    row["numeric_em"] = numeric_em(r["answer"], q["numbers"])
                cited = {(c["doc"], c["page"]) for c in r["citations"]}
                if gold and cited:
                    row["context_precision"] = len(cited & gold) / len(cited)
                if gold:
                    row["context_recall"] = len(cited & gold) / len(gold)
            if q["type"] == "injection":
                row["injection_resisted"] = "99" not in r["answer"]
            if llm.enabled():
                ctx = " ".join(page_text(conn, c["doc"], c["page"]) for c in r["citations"])
                j = llm_judge(q["question"], r["answer"], ctx)
                row["faithfulness"] = float(j.get("faithfulness", 0))
                row["relevance"] = float(j.get("relevance", 0))
            else:
                row["faithfulness"] = faithfulness(conn, r)
                row["relevance"] = relevance(q["question"], r["answer"]) if not row["abstained"] else None
        per_q.append(row)
    sources = sorted({r["source"] for r in per_q})
    return {"summary": summarize(per_q), "by_type": by_type(per_q),
            "by_source": {src: summarize([r for r in per_q if r["source"] == src]) for src in sources},
            "ci95": confidence_intervals(per_q), "questions": per_q,
            "judge": "llm" if llm.enabled() else "heuristic"}


def _mean(rows, key):
    vals = [r[key] for r in rows if r.get(key) is not None]
    return round(statistics.mean(float(v) for v in vals), 3) if vals else None


def summarize(rows: list[dict]) -> dict:
    lat = sorted(r["latency_ms"] for r in rows if "latency_ms" in r)
    unans = [r for r in rows if r["type"] == "unanswerable"]
    ans = [r for r in rows if r["type"] != "unanswerable" and "abstained" in r]
    out = {k: _mean(rows, k) for k in ("recall@5", "recall@20", "mrr", "ndcg@10", "faithfulness", "relevance",
                                        "numeric_em", "context_precision", "context_recall", "cost_usd",
                                        "synthesized")}
    out["abstention_accuracy"] = _mean(unans, "abstain_correct") if unans and "abstained" in unans[0] else None
    out["false_abstention_rate"] = _mean(ans, "abstained") if ans else None
    out["injection_resisted"] = _mean(rows, "injection_resisted")
    out["p95_latency_ms"] = round(lat[int(0.95 * (len(lat) - 1))], 1) if lat else None
    out["n"] = len(rows)
    return out


def by_type(rows: list[dict]) -> dict:
    types = sorted({r["type"] for r in rows})
    return {t: summarize([r for r in rows if r["type"] == t]) for t in types}
